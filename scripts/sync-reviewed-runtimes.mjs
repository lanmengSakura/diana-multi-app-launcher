import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const definitions = [['cursor', 'diana-cursor-theme', 'reviewed-cursor-3.17.21-v3'], ['grokbot', 'diana-grok-bot-theme', 'reviewed-grok-bot-0.28.0-v3']];
const lines = ['// Generated by scripts/sync-reviewed-runtimes.mjs; artwork uses the shared asset table.'];
for (const [target, repo, version] of definitions) {
  const source = path.resolve(root, '..', repo, 'dist/runtime');
  const manifest = fs.readFileSync(path.join(source, 'SHA256SUMS.txt'), 'utf8');
  const files = [];
  for (const line of manifest.trim().split('\n')) {
    const match = /^([a-f0-9]{64})  ([A-Za-z0-9._/-]+)$/.exec(line);
    if (!match || match[2].split('/').some(p => !p || p === '.' || p === '..')) throw new Error('Invalid reviewed manifest');
    const [, expected, relative] = match;
    const data = fs.readFileSync(path.join(source, relative));
    if (createHash('sha256').update(data).digest('hex') !== expected) throw new Error(`Source bundle hash mismatch: ${relative}`);
    if (relative.startsWith('assets/')) {
      const shared = fs.readFileSync(path.join(root, 'theme-preview', relative));
      if (!data.equals(shared)) throw new Error(`Shared artwork differs: ${relative}`);
    } else files.push([relative, data]);
  }
  files.push(['SHA256SUMS.txt', Buffer.from(manifest)]);
  for (const [relative, data] of files) {
    const dest = path.join(root, 'src-tauri/resources/theme-packs', target, 'runtime', relative);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, data);
  }
  const name = target.toUpperCase();
  lines.push(`pub const ${name}_VERSION: &str = ${JSON.stringify(version)};`);
  lines.push(`pub const ${name}_FILES: &[(&str, &[u8])] = &[`);
  for (const [relative] of files) lines.push(`    (${JSON.stringify(relative)}, include_bytes!(${JSON.stringify(`../resources/theme-packs/${target}/runtime/${relative}`)})),`);
  lines.push('];');
}
fs.writeFileSync(path.join(root, 'src-tauri/src/reviewed_adapter_files.rs'), lines.join('\n') + '\n');
console.log('Reviewed runtimes synchronized; shared PNGs not duplicated.');
